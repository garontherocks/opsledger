import { Pool } from 'pg';
import { config } from './config.ts';
import { Store } from './store.ts';
import { buildApp } from './app.ts';
import {AsyncOps} from './async-ops.ts';
const settings=config();const pool=new Pool({connectionString:settings.DATABASE_URL,connectionTimeoutMillis:2000});
const operations=await new AsyncOps(pool,settings.STORAGE_DIR,process.env.LAB_DB_BACKEND==='pglite'?'pglite':'postgres').start();
const app=await buildApp(new Store(pool,settings.AUTH_SECRET),settings,true,operations);
await app.listen({host:settings.BIND_HOST,port:settings.PORT});
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>{void app.close().then(()=>operations.stop()).then(()=>pool.end()).then(()=>process.exit(0));});
