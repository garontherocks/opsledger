import{test,expect}from'@playwright/test';
test('report incident, reload persistent list/detail, then revoke session',async({page})=>{
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await page.getByLabel('Email',{exact:true}).focus();
  await page.keyboard.press('Tab');
  await expect(page.getByLabel('Password',{exact:true})).toBeFocused();
  await page.getByLabel('Email',{exact:true}).fill('north-reporter@example.test');
  await page.getByLabel('Password',{exact:true}).fill('Incorrect synthetic password9!');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Invalid email or password');
  await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Report incident'})).toBeVisible();
  await expect(page.getByText('No incidents reported.',{exact:true})).toBeVisible();
  const title='Worker timeout '+crypto.randomUUID();
  await page.getByLabel('Title',{exact:true}).fill(title);
  await page.getByLabel('Description',{exact:true}).fill('Repeated worker timeouts need investigation');
  await page.getByLabel('Severity',{exact:true}).selectOption('high');
  await page.getByRole('button',{name:'Create incident',exact:true}).click();
  await expect(page.getByRole('article',{name:'Incident detail'})).toContainText(title);
  await page.reload();
  await page.getByRole('button',{name:title,exact:true}).click();
  await expect(page.getByRole('article',{name:'Incident detail'})).toContainText('reported');
  await page.screenshot({path:'evidence/phase2-incident-detail.png',fullPage:true});
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
});
