import {test,expect} from '@playwright/test';
test('editor publishes immutable versions, withdraws and inspects audit; Markdown is inert',async({page})=>{
 await page.goto('/');
 await page.getByLabel('Email',{exact:true}).fill('north-editor@example.test');
 await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_PASSWORD!);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('button',{name:'Open knowledge',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Runbooks',exact:true})).toBeVisible();
 const title='Knowledge '+crypto.randomUUID().replaceAll('-','');
 const body='# Synthetic guidance\n<script>window.__poison=true</script>\n<img src=x onerror="window.__poison=true">\n[Unsafe](javascript:alert(1))';
 await page.getByLabel('Runbook title',{exact:true}).fill(title);
 await page.getByLabel('Markdown body',{exact:true}).fill(body);
 await page.getByRole('button',{name:'Create runbook',exact:true}).click();
 const detail=page.getByRole('article',{name:'Runbook version'});
 await expect(detail).toContainText('Version 1 · draft');
 await page.getByRole('button',{name:'Publish version',exact:true}).click();
 await expect(detail).toContainText('Version 1 · published');
 const href=await detail.getByRole('link',{name:'Version JSON'}).getAttribute('href');expect(href).toBeTruthy();
 const original=(await (await page.request.get(href!)).json()) as {contentHash:string,body:string};
 await expect(detail.locator('img,script,iframe,a[href^="javascript:"]')).toHaveCount(0);
 expect(await page.evaluate(()=>(globalThis as unknown as Record<string,unknown>).__poison)).toBeUndefined();
 await page.getByLabel('Markdown body',{exact:true}).fill(body+'\nA revised fictional recovery step.');
 await page.getByRole('button',{name:'Save new version',exact:true}).click();
 await expect(detail).toContainText('Version 2 · draft');
 const historical=await (await page.request.get(href!)).json();
 expect(historical.contentHash).toBe(original.contentHash);expect(historical.body).toBe(original.body);
 await page.getByRole('button',{name:'Publish version',exact:true}).click();
 await expect(detail).toContainText('Version 2 · published');
 await page.getByRole('button',{name:'Withdraw version',exact:true}).click();
 await expect(detail).toContainText('Version 2 · withdrawn');
 await page.getByLabel('Keywords',{exact:true}).fill(title);
 await page.getByRole('button',{name:'Search runbooks',exact:true}).click();
 await expect(page.getByText('No matching runbooks.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Show audit',exact:true}).click();
 const audit=page.getByRole('region',{name:'Workspace audit'});await expect(audit).toContainText('runbook.withdraw');
 await page.screenshot({path:'evidence/phase4-knowledge.png',fullPage:true});
});
